import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

// The reviewed full-size master stays in docs/brand/logo.png. This display-sized
// derivative keeps standalone reports self-contained without embedding that master.
const root = resolve(import.meta.dirname, '..');
const logo = await readFile(resolve(root, 'docs/brand/logo-128.jpg'));
const output = `// Generated by scripts/generate-brand-assets.mjs; do not edit the image data.\nexport const PRODUCT_LOGO_DATA_URI = "data:image/jpeg;base64,${logo.toString('base64')}";\n`;
for (const module of ['core', 'cli']) {
  const target = resolve(root, `packages/${module}/src/brand.ts`);
  if (process.argv.includes('--check')) {
    if ((await readFile(target, 'utf8')).replace(/\r\n/g, '\n') !== output) throw new Error(`${module} runtime brand image is out of sync; run node scripts/generate-brand-assets.mjs.`);
  } else {
    await writeFile(target, output);
  }
}
