import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const theme = JSON.parse(await readFile(resolve(root, 'design/theme.json'), 'utf8'));
const colors = ['ink', 'inkHover', 'controlLine', 'muted', 'paper', 'wash', 'line', 'coral', 'orange', 'focus', 'error', 'errorWash', 'warning', 'warningWash', 'info', 'infoWash', 'success', 'successWash'];
const fontKeys = ['fontBody', 'fontHeading'];
const offlineFonts = new Set(['"Trebuchet MS"', 'Arial', 'sans-serif', '"Arial Rounded MT Bold"']);
const lengths = ['radiusControl', 'radiusPanel', 'radiusLarge', 'space1', 'space2', 'space3', 'space4', 'space5', 'space6', 'contentWidth', 'gutter', 'gutterSmall'];
const expected = [...colors, ...fontKeys, ...lengths];
if (Object.keys(theme).sort().join() !== [...expected].sort().join()) throw new Error('Design token keys differ from the fixed product contract.');
for (const key of colors) if (typeof theme[key] !== 'string' || !/^#[\da-f]{3}(?:[\da-f]{3})?$/i.test(theme[key])) throw new Error(`Invalid design color: ${key}`);
for (const key of fontKeys) {
  if (typeof theme[key] !== 'string' || !theme[key].split(',').every(font => offlineFonts.has(font))) throw new Error(`Invalid offline font stack: ${key}`);
}
for (const key of lengths) if (typeof theme[key] !== 'string' || !/^\d+(?:\.\d+)?px$/.test(theme[key])) throw new Error(`Invalid design length: ${key}`);
const cssName = key => key.replace(/[A-Z]/g, character => `-${character.toLowerCase()}`).replace(/(\D)(\d)/g, '$1-$2');
const css = `:root{${expected.map(key => `--${cssName(key)}:${theme[key]}`).join(';')}}`;
const moduleText = `// Generated by scripts/generate-design-system.mjs; do not edit.\nexport const PRODUCT_THEME = ${JSON.stringify(theme)} as const;\nexport const PRODUCT_THEME_CSS = ${JSON.stringify(css)};\n`;
const normalize = text => text.replace(/\r\n/g, '\n');
for (const module of ['core', 'cli']) {
  const path = resolve(root, `packages/${module}/src/design-system.ts`);
  if (process.argv.includes('--check')) {
    if (normalize(await readFile(path, 'utf8')) !== moduleText) throw new Error(`${module} design tokens are out of sync; run node scripts/generate-design-system.mjs.`);
  } else await writeFile(path, moduleText);
}
const markerStart = '/* Generated product tokens: start */';
const markerEnd = '/* Generated product tokens: end */';
const sitePath = resolve(root, 'docs/site/site.css');
const site = normalize(await readFile(sitePath, 'utf8'));
const prefix = `${markerStart}\n${css}\n${markerEnd}\n`;
const hasStart = site.startsWith(`${markerStart}\n`);
const end = site.indexOf(`${markerEnd}\n`);
if (hasStart && end < 0) throw new Error('Website design token marker is incomplete.');
const rest = hasStart ? site.slice(end + markerEnd.length + 1) : site;
for (const key of expected) if (new RegExp(`--${cssName(key)}\\s*:`).test(rest)) throw new Error(`Website overrides shared design token: ${key}`);
const output = prefix + rest;
if (process.argv.includes('--check')) {
  if (site !== output) throw new Error('Website design tokens are out of sync; run node scripts/generate-design-system.mjs.');
} else await writeFile(sitePath, output);
